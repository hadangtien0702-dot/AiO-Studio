/* 06/11 (de dung cho nguoi moi): tren Mac phim la ⌘, khong co Ctrl. Chuoi viet "Ctrl+Z" / "Ctrl + lan chuot" doi sang ⌘ khi chay
   tren Mac. Khong dong vao danh sach liet ke ("Ctrl / Alt / Shift") va "Cmd/Ctrl" (da co san ⌘). `mac` truyen vao de do duoc tren Windows. */
function chuanHoaMay(s, mac) {
  if (!mac || typeof s !== 'string' || s.indexOf('Ctrl') < 0) return s
  return s.replace(/(?<![/\w])Ctrl(?!\s*\/)(?!\w)/g, '\u2318')
}
const LA_MAC = typeof process !== 'undefined' && process.platform === 'darwin'

/** Ngon ngu mac dinh cho may MOI: he thong dang dung tieng Viet thi 'vi', con lai (ke ca rong / khong ro) 'en'. */
function ngonNguTuMay(locale) {
  return /^vi([-_]|$)/i.test(String(locale || '').trim()) ? 'vi' : 'en'
}

function t(lang, key) {
  const bang = DICH[lang] || DICH.vi
  const s = bang[key] != null ? bang[key] : (DICH.vi[key] != null ? DICH.vi[key] : key)
  return LA_MAC && !/Mac$/.test(key) ? chuanHoaMay(s, true) : s
}

module.exports = { DICH, t, chuanHoaMay, ngonNguTuMay }
